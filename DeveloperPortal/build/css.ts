// portal.css: Citizen's token values, the wiki's primitives, then the
// portal's own layout (DR-010 §13.2). Generated, so drift has one place to
// happen: vendor/, refreshed by `npm run sync`.
import { copyFileSync, mkdirSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);

/** Live values, read from Citizen on 2026-09-17 (DR-007 §2); motion.css is wrong. */
const EASINGS: Record<string, string> = {
	'--transition-timing-function-ease': 'cubic-bezier(0.2, 0, 0, 1)',
	'--transition-timing-function-ease-out': 'cubic-bezier(0.05, 0.7, 0.1, 1)',
	'--transition-timing-function-ease-in': 'cubic-bezier(0.3, 0, 0.8, 0.15)',
};

function fixMotion(css: string): string {
	for (const [name, value] of Object.entries(EASINGS)) {
		const pattern = new RegExp(`(${name}:\\s*)[^;]+;`);
		if (!pattern.test(css)) throw new Error(`motion.css: ${name} not found`);
		css = css.replace(pattern, `$1${value};`);
	}
	// Citizen's own reduced-motion rule lives in portal.css, once.
	return css.replace(/@media \(prefers-reduced-motion: reduce\) \{[\s\S]*?\n\}\n?/, '');
}

/** The tokens' .theme-dark block, applied by the reader's setting instead. */
function darkByPreference(css: string): string {
	const start = css.indexOf('.theme-dark {');
	if (start < 0) throw new Error('colors.css: no .theme-dark block');
	const end = css.indexOf('\n}', start);
	const body = css.slice(start + '.theme-dark {'.length, end);
	return css.slice(0, start) + `@media (prefers-color-scheme: dark) {\n:root {${body}\n}\n}` + css.slice(end + 2);
}

const FONTS = [
	{ pkg: '@fontsource/roboto', family: 'Roboto', weights: [400, 500, 700] },
	{ pkg: '@fontsource/roboto-mono', family: 'Roboto Mono', weights: [400, 500] },
];
const SUBSETS = ['latin', 'latin-ext'];

/** Self-hosted, so a page view sends nothing to Google. */
function fonts(out: string): string {
	mkdirSync(join(out, 'fonts'), { recursive: true });
	const faces: string[] = [];
	for (const font of FONTS) {
		const root = dirname(require.resolve(`${font.pkg}/package.json`));
		for (const weight of font.weights) {
			const css = readFileSync(join(root, `${weight}.css`), 'utf8');
			for (const block of css.match(/\/\* [\w-]+ \*\/\s*@font-face \{[\s\S]*?\}/g) ?? []) {
				const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)![1];
				if (!SUBSETS.some((subset) => file.endsWith(`-${subset}-${weight}-normal.woff2`))) continue;
				copyFileSync(join(root, 'files', file), join(out, 'fonts', file));
				const range = /unicode-range:\s*([^;]+);/.exec(block)![1];
				faces.push(`@font-face{font-family:'${font.family}';font-style:normal;font-display:swap;font-weight:${weight};src:url(/fonts/${file}) format('woff2');unicode-range:${range};}`);
			}
		}
	}
	if (faces.length === 0) throw new Error('no font faces found: has @fontsource changed its layout?');
	return faces.join('\n');
}

/** Every var() the stylesheet reads that nothing in it declares. */
function undeclared(css: string): string[] {
	const declared = new Set([...css.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]));
	const used = new Set([...css.matchAll(/var\(\s*(--[\w-]+)/g)].map((m) => m[1]));
	return [...used].filter((name) => !declared.has(name)).sort();
}

/** Custom properties the primitives read from a surface, never declared globally. */
const SURFACE_SET = new Set(['--t-segmented-w', '--t-segmented-h', '--t-segmented-x', '--t-segmented-y', '--t-segmented-duration', '--t-icon-url', '--t-photo-placeholder-size']);

export function buildCss(root: string, out: string): string {
	const tokens = ['colors', 'typography', 'borders', 'spacing', 'elevation', 'motion'].map((name) => {
		let css = readFileSync(join(root, 'vendor/tokens', `${name}.css`), 'utf8');
		if (name === 'motion') css = fixMotion(css);
		if (name === 'colors') css = darkByPreference(css);
		return `/* vendor/tokens/${name}.css */\n${css}`;
	});
	const css = [
		'/* Generated by build/css.ts from vendor/ and content/portal.css. Edit those. */',
		fonts(out),
		...tokens,
		`/* vendor/citizen.css */\n${readFileSync(join(root, 'vendor/citizen.css'), 'utf8')}`,
		'/* vendor/primitives.css: the first block of MediaWiki:Common.css */',
		readFileSync(join(root, 'vendor/primitives.css'), 'utf8'),
		readFileSync(join(root, 'content/portal.css'), 'utf8'),
	].join('\n\n');

	const missing = undeclared(css).filter((name) => !SURFACE_SET.has(name));
	if (missing.length) console.warn(`portal.css reads tokens nothing declares: ${missing.join(', ')}`);
	return css;
}
